/* =========================================================
   RESET PAGE CLASSES
========================================================= */

function u9ProfileResetPageClasses() {

  for (
    let pageNumber = 1;
    pageNumber <= 7;
    pageNumber++
  ) {

    const pageData =
      u9ProfilePages[
        pageNumber
      ];


    if (
      !pageData ||
      !pageData.page
    ) {

      continue;

    }


    pageData.page.classList.remove(
      "U9-profile-page-active"
    );


    pageData.page.classList.remove(
      "U9-profile-page-current"
    );


    pageData.page.classList.remove(
      "U9-profile-page-slide-left"
    );


    pageData.page.classList.remove(
      "U9-profile-page-slide-right"
    );


    pageData.page.classList.remove(
      "U9-profile-page-slide-from-left"
    );


    pageData.page.classList.remove(
      "U9-profile-page-slide-from-right"
    );

  }

}


/* =========================================================
   RESET TO PROFILE HOME
========================================================= */

function u9ProfileGoHome(
  immediate = false
) {

  if (
    !profileHome
  ) {

    return;

  }


  /*
    Stop any current
    page animation.
  */

  u9ProfilePageAnimating =
    false;


  /*
    Reset every internal page.
  */

  u9ProfileResetPageClasses();


  /*
    Show Home.
  */

  profileHome.classList.add(
    "U9-profile-page-active"
  );


  profileHome.classList.add(
    "U9-profile-page-current"
  );


  /*
    Home is page 0.
  */

  u9ProfileCurrentPage =
    0;


  /*
    Scroll Home back to top.
  */

  if (
    profileHomeBody
  ) {

    profileHomeBody.scrollTop =
      0;

  }


  /*
    Reset all internal page
    scroll positions.
  */

  for (
    let pageNumber = 1;
    pageNumber <= 7;
    pageNumber++
  ) {

    const pageData =
      u9ProfilePages[
        pageNumber
      ];


    if (
      pageData?.body
    ) {

      pageData.body.scrollTop =
        0;

    }

  }

}


/* =========================================================
   PREPARE PAGE
========================================================= */

function u9ProfilePreparePage(
  pageNumber
) {

  const pageData =
    u9ProfilePages[
      pageNumber
    ];


  if (
    !pageData ||
    !pageData.page
  ) {

    return false;

  }


  /*
    Page title.
  */

  if (
    pageData.title
  ) {

    pageData.title.textContent =
      u9ProfilePageTitles[
        pageNumber
      ] ||
      `Button ${pageNumber}`;

  }


  /*
    Page icon.

    All pages currently use
    the same U9website.svg.

    You can change each HTML
    src independently later.
  */

  if (
    pageData.icon
  ) {

    pageData.icon.src =
      u9ProfilePageIcon;

  }


  /*
    Reset page scroll.
  */

  if (
    pageData.body
  ) {

    pageData.body.scrollTop =
      0;

  }


  return true;

}


/* =========================================================
   OPEN PROFILE PAGE
========================================================= */

function u9ProfileOpenPage(
  pageNumber
) {

  if (
    u9ProfilePageAnimating
  ) {

    return false;

  }


  if (
    pageNumber < 1 ||
    pageNumber > 7
  ) {

    return false;

  }


  const nextPage =
    u9ProfilePages[
      pageNumber
    ];


  if (
    !nextPage ||
    !nextPage.page
  ) {

    return false;

  }


  /*
    If already on this page,
    do nothing.
  */

  if (
    u9ProfileCurrentPage ===
    pageNumber
  ) {

    return true;

  }


  /*
    Only allow opening
    internal pages from Home
    or another page.

    Forward animation.
  */

  const currentPageNumber =
    u9ProfileCurrentPage;


  let currentPage =
    null;


  if (
    currentPageNumber === 0
  ) {

    currentPage =
      profileHome;

  }

  else {

    currentPage =
      u9ProfilePages[
        currentPageNumber
      ]?.page ||
      null;

  }


  /*
    Prepare next page.
  */

  u9ProfilePreparePage(
    pageNumber
  );


  /*
    If current page does
    not exist, simply activate.
  */

  if (
    !currentPage
  ) {

    u9ProfileResetPageClasses();


    nextPage.page.classList.add(
      "U9-profile-page-active"
    );


    nextPage.page.classList.add(
      "U9-profile-page-current"
    );


    u9ProfileCurrentPage =
      pageNumber;


    return true;

  }


  /*
    Start animation lock.
  */

  u9ProfilePageAnimating =
    true;


  /*
    Make next page start
    from the right.
  */

  nextPage.page.classList.remove(
    "U9-profile-page-active"
  );


  nextPage.page.classList.remove(
    "U9-profile-page-current"
  );


  nextPage.page.classList.remove(
    "U9-profile-page-slide-left"
  );


  nextPage.page.classList.remove(
    "U9-profile-page-slide-right"
  );


  nextPage.page.classList.remove(
    "U9-profile-page-slide-from-left"
  );


  nextPage.page.classList.add(
    "U9-profile-page-slide-from-right"
  );


  /*
    Force browser layout so
    the starting position is
    registered before animation.
  */

  void nextPage.page.offsetWidth;


  /*
    Current page moves left.
  */

  currentPage.classList.remove(
    "U9-profile-page-active"
  );


  currentPage.classList.remove(
    "U9-profile-page-current"
  );


  currentPage.classList.remove(
    "U9-profile-page-slide-right"
  );


  currentPage.classList.add(
    "U9-profile-page-slide-left"
  );


  /*
    Next page moves to center.
  */

  nextPage.page.classList.remove(
    "U9-profile-page-slide-from-right"
  );


  nextPage.page.classList.add(
    "U9-profile-page-active"
  );


  nextPage.page.classList.add(
    "U9-profile-page-current"
  );


  /*
    Update current page.
  */

  u9ProfileCurrentPage =
    pageNumber;


  /*
    Finish animation.
  */

  setTimeout(
    function () {

      if (
        currentPage
      ) {

        currentPage.classList.remove(
          "U9-profile-page-slide-left"
        );

      }


      u9ProfilePageAnimating =
        false;

    },
    380
  );


  return true;

}


/* =========================================================
   BACK TO PREVIOUS PAGE
========================================================= */

function u9ProfileGoBack() {

  if (
    u9ProfilePageAnimating
  ) {

    return false;

  }


  /*
    Already Home.
  */

  if (
    u9ProfileCurrentPage ===
    0
  ) {

    return true;

  }


  const currentPageNumber =
    u9ProfileCurrentPage;


  const currentPage =
    u9ProfilePages[
      currentPageNumber
    ]?.page ||
    null;


  /*
    Current page always
    returns to Home.

    The requested architecture
    uses Home as the previous
    page for all Button 1-7.
  */

  const previousPage =
    profileHome;


  if (
    !currentPage ||
    !previousPage
  ) {

    u9ProfileGoHome(
      true
    );

    return true;

  }


  /*
    Start animation lock.
  */

  u9ProfilePageAnimating =
    true;


  /*
    Previous page starts
    from the left.
  */

  previousPage.classList.remove(
    "U9-profile-page-active"
  );


  previousPage.classList.remove(
    "U9-profile-page-current"
  );


  previousPage.classList.remove(
    "U9-profile-page-slide-left"
  );


  previousPage.classList.remove(
    "U9-profile-page-slide-right"
  );


  previousPage.classList.remove(
    "U9-profile-page-slide-from-right"
  );


  previousPage.classList.add(
    "U9-profile-page-slide-from-left"
  );


  /*
    Force layout.
  */

  void previousPage.offsetWidth;


  /*
    Current page moves right.
  */

  currentPage.classList.remove(
    "U9-profile-page-active"
  );


  currentPage.classList.remove(
    "U9-profile-page-current"
  );


  currentPage.classList.remove(
    "U9-profile-page-slide-left"
  );


  currentPage.classList.add(
    "U9-profile-page-slide-right"
  );


  /*
    Home moves from left
    to center.
  */

  previousPage.classList.remove(
    "U9-profile-page-slide-from-left"
  );


  previousPage.classList.add(
    "U9-profile-page-active"
  );


  previousPage.classList.add(
    "U9-profile-page-current"
  );


  /*
    Update state.
  */

  u9ProfileCurrentPage =
    0;


  /*
    Home scroll position.
  */

  if (
    profileHomeBody
  ) {

    profileHomeBody.scrollTop =
      0;

  }


  /*
    Finish animation.
  */

  setTimeout(
    function () {

      currentPage.classList.remove(
        "U9-profile-page-slide-right"
      );


      u9ProfilePageAnimating =
        false;

    },
    380
  );


  return true;

}


