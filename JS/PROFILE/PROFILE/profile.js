/* =========================================================
   LOAD PROFILE AVATAR
========================================================= */

async function u9ProfileLoadAvatarFromUser(
  user
) {

  /*
    Always start with
    frontend defaults.

    Avatar:
    embedded SVG

    Frame:
    ordinary.svg
  */

  u9ProfileResetAvatar();


  /*
    =========================
    NO USER
    =========================
  */

  if (
    !user
  ) {

    return false;

  }


  try {

    /*
      =========================
      USER AVATAR
      =========================
    */

    const avatar =
      user.avatar ||
      null;


    const avatarUrl =
      avatar?.url ||
      "";


    /*
      =========================
      USER HAS AVATAR
      =========================
    */

    if (
      avatarUrl &&
      u9ProfileAvatarImage
    ) {

      u9ProfileAvatarImage.dataset.u9Fallback =
        "false";


      u9ProfileAvatarImage.src =
        avatarUrl;

    }


    /*
      =========================
      NO USER AVATAR
      =========================
    */

    else if (
      u9ProfileAvatarImage
    ) {

      u9ProfileAvatarImage.dataset.u9Fallback =
        "false";


      u9ProfileAvatarImage.src =
        u9ProfileDefaultAvatar;

    }


    /*
      =========================
      USER FRAME
      =========================
    */

    const frameType =
      user.avatar_frame_type ||
      "default";


    const frameId =
      user.avatar_frame_id ||
      null;


    const frameLoaded =
      await u9ProfileLoadFrame(
        frameType,
        frameId
      );


    /*
      Frame failed:
      use frontend defaults.
    */

    if (
      !frameLoaded
    ) {

      u9ProfileResetAvatar();

      return false;

    }


    return true;

  }

  catch (
    error
  ) {

    /*
      Unexpected error:
      frontend defaults.
    */

    u9ProfileResetAvatar();

    return false;

  }

}


/* =========================================================
   LOAD PROFILE
========================================================= */

async function u9ProfileLoad() {

  /*
    =========================
    SHOW LOADING
    =========================
  */

  u9ProfileShowLoading();


  /*
    Start with frontend defaults.

    Avatar -> embedded SVG
    Frame  -> ordinary.svg
  */

  u9ProfileResetAvatar();


  /*
    =========================
    U9 USER NOT AVAILABLE
    =========================
  */

  if (
    !window.U9User
  ) {

    console.warn(
      "U9User is not available."
    );


    u9ProfileResetAvatar();


    u9ProfileHideLoading();


    return;

  }


  /*
    =========================
    GET USER
    =========================
  */

  const user =
    window.U9User.get();


  /*
    =========================
    NOT LOGGED IN
    =========================
  */

  if (
    !window.U9User.isLoggedIn() ||
    !user
  ) {

    u9ProfileResetAvatar();


    u9ProfileHideLoading();


    return;

  }


  /*
    =========================
    LOAD
    =========================
  */

  try {

    /*
      =========================
      DISPLAY USER
      =========================
    */

    u9ProfileDisplayUser(
      user
    );


    /*
      =========================
      LOAD AVATAR + FRAME
      =========================
    */

    const avatarLoaded =
      await u9ProfileLoadAvatarFromUser(
        user
      );


    /*
      Any failure:
      frontend defaults.
    */

    if (
      !avatarLoaded
    ) {

      u9ProfileResetAvatar();

    }


    /*
      =========================
      HIDE LOADING
      =========================
    */

    u9ProfileHideLoading();


    console.log(
      "Profile Loaded:",
      user
    );

  }

  catch (
    error
  ) {

    /*
      Any unexpected profile error.
    */

    console.error(
      "Load profile failed:",
      error
    );


    /*
      Frontend defaults.
    */

    u9ProfileResetAvatar();


    u9ProfileHideLoading();

  }

}


