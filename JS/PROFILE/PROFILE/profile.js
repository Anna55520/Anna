/* =========================================================
   LOAD FREE / PAID FRAME
========================================================= */

async function u9ProfileLoadFrame(
  frameType,
  frameId
) {

  /*
    =========================
    DATABASE DEFAULT FRAME
    =========================
  */

  if (
    !frameType ||
    frameType === "default"
  ) {

    if (
      u9ProfileAvatarFrame
    ) {

      u9ProfileAvatarFrame.dataset.u9Fallback =
        "false";


      u9ProfileAvatarFrame.src =
        u9ProfileDefaultFrame;

    }


    return true;

  }


  /*
    =========================
    NO FRAME ID
    =========================
  */

  if (
    !frameId
  ) {

    if (
      u9ProfileAvatarFrame
    ) {

      u9ProfileAvatarFrame.dataset.u9Fallback =
        "false";


      u9ProfileAvatarFrame.src =
        u9ProfileDefaultFrame;

    }


    return true;

  }


  let requestUrl =
    "";


  /*
    =========================
    FREE FRAME
    =========================
  */

  if (
    frameType === "free"
  ) {

    requestUrl =
      u9ProfileFreeFrameUrl;

  }


  /*
    =========================
    PAID FRAME
    =========================
  */

  else if (
    frameType === "paid"
  ) {

    requestUrl =
      u9ProfilePaidFrameUrl;

  }


  /*
    =========================
    UNKNOWN FRAME TYPE
    =========================
  */

  else {

    u9ProfileResetAvatar();

    return false;

  }


  /*
    =========================
    REQUEST
    =========================
  */

  try {

    const response =
      await fetch(
        requestUrl,
        {
          method: "GET"
        }
      );


    /*
      =========================
      REQUEST FAILED
      =========================
    */

    if (
      !response.ok
    ) {

      u9ProfileResetAvatar();

      return false;

    }


    /*
      =========================
      JSON
      =========================
    */

    const result =
      await response.json();


    const frames =
      result.frames ||
      result.data?.frames ||
      [];


    /*
      =========================
      FIND CURRENT FRAME
      =========================
    */

    const currentFrame =
      frames.find(
        (frame) =>
          frame.id === frameId
      );


    /*
      =========================
      FRAME NOT FOUND
      =========================
    */

    if (
      !currentFrame
    ) {

      u9ProfileResetAvatar();

      return false;

    }


    /*
      =========================
      FRAME SVG NOT FOUND
      =========================
    */

    if (
      !currentFrame.svg
    ) {

      u9ProfileResetAvatar();

      return false;

    }


    /*
      =========================
      LOAD REAL FRAME
      =========================
    */

    if (
      u9ProfileAvatarFrame
    ) {

      u9ProfileAvatarFrame.dataset.u9Fallback =
        "false";


      u9ProfileAvatarFrame.src =
        currentFrame.svg;

    }


    return true;

  }

  catch (
    error
  ) {

    /*
      Network error
      Offline
      Connection changed
      Fetch failed

      Use frontend defaults.
    */

    u9ProfileResetAvatar();

    return false;

  }

}


