/* =========================================================
   CHECK PROFILE AUTH
========================================================= */

function u9ProfileCanOpen() {

  if (
    !window.U9User
  ) {

    console.warn(
      "U9User is not available."
    );


    return false;

  }


  if (
    !window.U9User.isLoggedIn()
  ) {

    return false;

  }


  if (
    !window.U9User.get()
  ) {

    return false;

  }


  return true;

}


/* =========================================================
   OPEN PROFILE MODAL
========================================================= */

function openProfileModal() {

  if (
    !profileModal ||
    !profileModalContent
  ) {

    return false;

  }


  if (
    !u9ProfileCanOpen()
  ) {

    console.warn(
      "Profile cannot open: user is not authenticated."
    );


    return false;

  }


  /*
    Every time Profile Window
    opens, start from Home.
  */

  u9ProfileGoHome(
    true
  );


  /*
    REMOVE CLOSING
  */

  profileModal.classList.remove(
    "modal-closing"
  );


  /*
    OPEN
  */

  profileModal.classList.add(
    "modal-open"
  );


  /*
    USER BUTTON ACTIVE
  */

  if (
    profileUserButton
  ) {

    profileUserButton.classList.add(
      "account-open"
    );

  }


  /*
    LOAD PROFILE
  */

  u9ProfileLoad();


  return true;

}


/* =========================================================
   CLOSE PROFILE MODAL
========================================================= */

function closeProfileModal() {

  if (
    !profileModal ||
    !profileModalContent
  ) {

    return false;

  }


  if (
    !profileModal.classList.contains(
      "modal-open"
    )
  ) {

    return true;

  }


  /*
    REMOVE OPEN
  */

  profileModal.classList.remove(
    "modal-open"
  );


  /*
    START CLOSING
  */

  profileModal.classList.add(
    "modal-closing"
  );


  /*
    USER BUTTON INACTIVE
  */

  if (
    profileUserButton
  ) {

    profileUserButton.classList.remove(
      "account-open"
    );

  }


  let closeFinished =
    false;


  function finishClose() {

    if (
      closeFinished
    ) {

      return;

    }


    closeFinished =
      true;


    /*
      REMOVE CLOSING
    */

    profileModal.classList.remove(
      "modal-closing"
    );


    /*
      REMOVE EVENT
    */

    profileModalContent.removeEventListener(
      "transitionend",
      handleCloseAnimation
    );

  }


  function handleCloseAnimation(
    event
  ) {

    if (
      event.propertyName !==
      "transform"
    ) {

      return;

    }


    finishClose();

  }


  profileModalContent.addEventListener(
    "transitionend",
    handleCloseAnimation
  );


  setTimeout(
    finishClose,
    700
  );


  return true;

}


/* =========================================================
   TOGGLE PROFILE MODAL
========================================================= */

async function toggleProfileModal() {

  if (
    !profileModal
  ) {

    return false;

  }


  if (
    profileModal.classList.contains(
      "modal-open"
    )
  ) {

    if (
      window.U9WindowManager
    ) {

      await window.U9WindowManager.close(
        "profile"
      );

    }

    else {

      closeProfileModal();

    }


    return true;

  }


  if (
    window.U9WindowManager
  ) {

    return await window.U9WindowManager.open(
      "profile"
    );

  }


  return openProfileModal();

}


