
/* =================================================
   U9 MESSAGE NORMAL MODAL
   File: JS/NORMAL/normal-message.js

   Responsibilities:
   - Open and close Message modal
   - Navigate between Message pages
   - Open and close Chat page
   - Manage Message header and back navigation
   - Pass friend avatar and frame URLs to chat.js
   - Move keyboard focus before hiding a page
   - Clean up chat state when leaving Chat

   Chat UI and message operations belong in:
   JS/NORMAL/MESSAGE/chat.js
================================================= */

(function () {
  "use strict";

  /* =================================================
     MODAL ELEMENTS
  ================================================= */

  const messageModal = document.getElementById(
    "U9-message-normal-modal"
  );

  const messageModalContent = document.getElementById(
    "U9-message-normal-modal-content"
  );

  const messageModalTitle = document.getElementById(
    "U9-message-normal-modal-title"
  );

  const messageModalTitleText = document.getElementById(
    "U9-message-normal-modal-title-text"
  );

  const messageModalClose = document.getElementById(
    "U9-message-normal-modal-close"
  );

  const messageNavigation = document.getElementById(
    "Message-model-navigation"
  );

  const messagePagesContainer = document.getElementById(
    "Message-model-pages"
  );

  /* =================================================
     PAGE CONFIGURATION
  ================================================= */

  const messagePageConfig = {
    "friends": {
      buttonId: "Message-model-friends-button",
      pageId: "Message-model-friends-page",
      title: "Friend",
      initializer: "initializeFriendsPage"
    },

    "add-friends": {
      buttonId: "Message-model-add-friends-button",
      pageId: "Message-model-add-friends-page",
      title: "Add Friend",
      initializer: "initializeAddFriendsPage"
    },

    "group": {
      buttonId: "Message-model-group-button",
      pageId: "Message-model-group-page",
      title: "Group",
      initializer: "initializeGroupPage"
    },

    "customer-service": {
      buttonId: "Message-model-customer-service-button",
      pageId: "Message-model-customer-service-page",
      title: "Customer Service",
      initializer: "initializeCustomerServicePage"
    }
  };

  const BACK_ICON_URL = "/SSVG/account/back.svg";

  /*
   * This is the temporary fallback used while a chat
   * target's real avatar URL is unavailable.
   *
   * The API may return the user's actual selected avatar
   * once their profile has been loaded.
   */
  const DEFAULT_CHAT_AVATAR =
    "/SSVG/account/account-edit-button.svg";

  const DEFAULT_CHAT_FRAME =
    "/SSVG/avatar/ordinary.svg";

  /* =================================================
     STATE

     null  = Message home
     key   = normal inner page
     chat  = Chat page
  ================================================= */

  let currentMessagePage = null;
  let currentChatUser = null;
  let closeAnimationTimer = null;
  let messageInitialized = false;

  /* =================================================
     PAGE ELEMENTS
  ================================================= */

  function getMessagePageElements() {
    const elements = {};

    Object.keys(messagePageConfig).forEach(function (key) {
      const config = messagePageConfig[key];

      elements[key] = {
        button: document.getElementById(config.buttonId),
        page: document.getElementById(config.pageId)
      };
    });

    return elements;
  }

  function getChatPage() {
    return document.getElementById(
      "Message-model-chat-page"
    );
  }

  function getMessageHome() {
    return document.getElementById(
      "Message-model-home"
    );
  }

  /* =================================================
     IMAGE URL NORMALIZATION
  ================================================= */

  function normalizeImageURL(value, fallback) {
    if (typeof value !== "string") {
      return fallback;
    }

    const url = value.trim();

    if (!url) {
      return fallback;
    }

    /*
     * Allow HTTPS images, local absolute paths,
     * and SVG Data URLs generated by message-api.
     */
    if (
      /^https:\/\//i.test(url) ||
      (
        url.startsWith("/") &&
        !url.startsWith("//")
      ) ||
      /^data:image\/svg\+xml;charset=UTF-8,/i.test(url)
    ) {
      return url;
    }

    return fallback;
  }

  function getUserAvatarURL(user) {
    if (!user || typeof user !== "object") {
      return DEFAULT_CHAT_AVATAR;
    }

    const avatarValue =
      user.avatar_url ||
      user.avatarUrl ||
      (
        typeof user.avatar === "string"
          ? user.avatar
          : user.avatar?.url
      );

    return normalizeImageURL(
      avatarValue,
      DEFAULT_CHAT_AVATAR
    );
  }

  function getUserAvatarFrameURL(user) {
    if (!user || typeof user !== "object") {
      return DEFAULT_CHAT_FRAME;
    }

    const frameValue =
      user.avatar_frame_url ||
      user.avatarFrameUrl ||
      user.avatarFrame ||
      "";

    return normalizeImageURL(
      frameValue,
      DEFAULT_CHAT_FRAME
    );
  }

  /* =================================================
     CHAT CLEANUP
  ================================================= */

  function stopCurrentChat() {
    /*
     * chat.js owns message state and polling/realtime cleanup.
     */
    if (typeof window.closeChatPage === "function") {
      try {
        window.closeChatPage();
      } catch (error) {
        console.error(
          "U9 Message: Failed to close Chat page.",
          error
        );
      }
    } else {
      /*
       * Fallback if chat.js has not loaded.
       */
      const chatPage = getChatPage();

      if (chatPage) {
        chatPage.classList.remove("active");
        chatPage.classList.remove("is-active");
        chatPage.hidden = true;
        chatPage.setAttribute("aria-hidden", "true");
      }
    }
  }

  /* =================================================
     FOCUS MANAGEMENT

     Move focus before hiding an element that currently
     contains focus. This prevents aria-hidden warnings.
  ================================================= */

  function moveFocusOutOfPages() {
    const activeElement = document.activeElement;

    if (!activeElement) {
      return;
    }

    const pageElements = getMessagePageElements();
    let focusIsInsidePage = false;

    Object.keys(pageElements).forEach(function (key) {
      const page = pageElements[key].page;

      if (
        page &&
        page.contains(activeElement)
      ) {
        focusIsInsidePage = true;
      }
    });

    const chatPage = getChatPage();

    if (
      chatPage &&
      chatPage.contains(activeElement)
    ) {
      focusIsInsidePage = true;
    }

    if (!focusIsInsidePage) {
      return;
    }

    /*
     * The Message header close/back button remains outside
     * the pages being hidden.
     */
    if (
      messageModalClose &&
      !messageModalClose.disabled
    ) {
      messageModalClose.focus({
        preventScroll: true
      });
      return;
    }

    /*
     * Fallback for unusual HTML or disabled controls.
     */
    if (
      typeof activeElement.blur === "function"
    ) {
      activeElement.blur();
    }
  }

  /* =================================================
     HEADER TITLE
  ================================================= */

  function getMessageHeaderTitle() {
    if (currentMessagePage === "chat") {
      return currentChatUser?.name || "Chat";
    }

    if (
      currentMessagePage &&
      messagePageConfig[currentMessagePage]
    ) {
      return messagePageConfig[currentMessagePage].title;
    }

    return "Message";
  }

  function setMessageHeader(isInnerPage) {
    if (!messageModalTitle || !messageModalClose) {
      return;
    }

    const title = getMessageHeaderTitle();

    /*
     * Prefer the dedicated title span in the updated HTML.
     */
    if (messageModalTitleText) {
      messageModalTitleText.textContent = title;
    } else {
      const existingTitleText = Array.from(
        messageModalTitle.childNodes
      ).find(function (node) {
        return (
          node.nodeType === Node.TEXT_NODE &&
          node.textContent.trim() !== ""
        );
      });

      if (existingTitleText) {
        existingTitleText.textContent = " " + title + " ";
      }
    }

    if (isInnerPage) {
      messageModalClose.classList.remove(
        "message-home-close"
      );

      messageModalClose.classList.add(
        "message-back-button"
      );

      messageModalClose.replaceChildren();

      const backIcon = document.createElement("img");

      backIcon.src = BACK_ICON_URL;
      backIcon.alt = "";

      backIcon.setAttribute(
        "aria-hidden",
        "true"
      );

      messageModalClose.appendChild(backIcon);

      messageModalClose.setAttribute(
        "aria-label",
        "Back"
      );

      messageModalClose.setAttribute(
        "title",
        "Back"
      );
    } else {
      messageModalClose.classList.remove(
        "message-back-button"
      );

      messageModalClose.classList.add(
        "message-home-close"
      );

      messageModalClose.replaceChildren();
      messageModalClose.textContent = "×";

      messageModalClose.setAttribute(
        "aria-label",
        "Close Message"
      );

      messageModalClose.setAttribute(
        "title",
        "Close"
      );
    }
  }

  /* =================================================
     HIDE ALL PAGES
  ================================================= */

  function hideAllMessagePages() {
    /*
     * Important: move focus before setting hidden=true.
     */
    moveFocusOutOfPages();

    const pageElements = getMessagePageElements();

    Object.keys(pageElements).forEach(function (key) {
      const page = pageElements[key].page;

      if (!page) {
        return;
      }

      page.classList.remove("active");

      page.hidden = true;

      page.setAttribute(
        "aria-hidden",
        "true"
      );
    });

    const chatPage = getChatPage();

    if (chatPage) {
      chatPage.classList.remove("active");
      chatPage.classList.remove("is-active");

      chatPage.hidden = true;

      chatPage.setAttribute(
        "aria-hidden",
        "true"
      );
    }
  }

  /* =================================================
     NAVIGATION SELECTION
  ================================================= */

  function clearNavigationSelection() {
    const pageElements = getMessagePageElements();

    Object.keys(pageElements).forEach(function (key) {
      const button = pageElements[key].button;

      if (!button) {
        return;
      }

      button.classList.remove("active");

      button.setAttribute(
        "aria-selected",
        "false"
      );
    });
  }

  /* =================================================
     MESSAGE HOME
  ================================================= */

  function showMessageHome() {
    if (!messageModalContent) {
      return false;
    }

    /*
     * Move focus before chat.js hides the chat page.
     */
    moveFocusOutOfPages();

    if (currentMessagePage === "chat") {
      stopCurrentChat();
    }

    currentMessagePage = null;
    currentChatUser = null;

    window.messageChatReturnPage = null;

    messageModalContent.classList.add("message-home");

    messageModalContent.classList.remove(
      "message-inner-page"
    );

    clearNavigationSelection();

    setMessageHeader(false);

    hideAllMessagePages();

    return true;
  }

  /* =================================================
     INITIALIZE NORMAL PAGE
  ================================================= */

  function initializeInnerPage(pageKey) {
    const config = messagePageConfig[pageKey];

    if (!config || !config.initializer) {
      return;
    }

    const initializer = window[config.initializer];

    if (typeof initializer !== "function") {
      console.warn(
        "U9 Message: Page initializer is unavailable:",
        config.initializer
      );

      return;
    }

    try {
      const result = initializer();

      if (
        result &&
        typeof result.catch === "function"
      ) {
        result.catch(function (error) {
          console.error(
            "U9 Message: Async page initialization failed:",
            pageKey,
            error
          );
        });
      }
    } catch (error) {
      console.error(
        "U9 Message: Page initialization failed:",
        pageKey,
        error
      );
    }
  }

  /* =================================================
     SWITCH NORMAL PAGE
  ================================================= */

  function switchMessagePage(pageKey) {
    const config = messagePageConfig[pageKey];

    if (!config) {
      console.warn(
        "U9 Message: Unknown page:",
        pageKey
      );

      return false;
    }

    if (!messageModalContent) {
      console.warn(
        "U9 Message: Modal content is missing."
      );

      return false;
    }

    const elements = getMessagePageElements();
    const target = elements[pageKey];

    if (
      !target ||
      !target.button ||
      !target.page
    ) {
      console.warn(
        "U9 Message: Page elements are missing:",
        pageKey
      );

      return false;
    }

    /*
     * If leaving Chat through this public API, stop its
     * polling and clear its active conversation.
     */
    if (currentMessagePage === "chat") {
      moveFocusOutOfPages();
      stopCurrentChat();
      window.messageChatReturnPage = null;
    }

    currentMessagePage = pageKey;
    currentChatUser = null;

    messageModalContent.classList.remove(
      "message-home"
    );

    messageModalContent.classList.add(
      "message-inner-page"
    );

    clearNavigationSelection();

    setMessageHeader(true);

    hideAllMessagePages();

    target.button.classList.add("active");

    target.button.setAttribute(
      "aria-selected",
      "true"
    );

    target.page.hidden = false;

    target.page.classList.add("active");

    target.page.setAttribute(
      "aria-hidden",
      "false"
    );

    initializeInnerPage(pageKey);

    return true;
  }

  /* =================================================
     OPEN CHAT PAGE

     Chat UI and message operations belong in chat.js.
  ================================================= */

  function openMessageChat(user) {
    const chatPage = getChatPage();

    if (!chatPage || !messageModalContent) {
      console.warn(
        "U9 Message: #Message-model-chat-page was not found."
      );

      return false;
    }

    if (
      !user ||
      typeof user !== "object" ||
      !user.id
    ) {
      console.warn(
        "U9 Message: A valid chat target ID is required.",
        user
      );

      return false;
    }

    /*
     * Remember the page that opened the Chat page.
     *
     * Do not overwrite the original return page when
     * changing conversations while Chat is already open.
     */
    if (currentMessagePage !== "chat") {
      const currentReturnPage =
        currentMessagePage &&
        messagePageConfig[currentMessagePage]
          ? currentMessagePage
          : null;

      const requestedReturnPage =
        window.messageChatReturnPage &&
        messagePageConfig[window.messageChatReturnPage]
          ? window.messageChatReturnPage
          : null;

      window.messageChatReturnPage =
        currentReturnPage || requestedReturnPage;
    }

    /*
     * Accept both string URLs and user.avatar.url objects.
     */
    const avatarURL = getUserAvatarURL(user);

    const avatarFrameURL =
      getUserAvatarFrameURL(user);

    currentChatUser = {
      id: String(
        user.id ||
        user.user_id ||
        user.group_id ||
        user.conversation_id
      ),

      name: String(
        user.name ||
        user.username ||
        user.group_name ||
        (
          user.type === "customer_service"
            ? "Customer Service"
            : user.type === "group"
              ? "Group"
              : "User"
        )
      ),

      /*
       * Keep the avatar fields expected by chat.js.
       */
      avatar: avatarURL,
      avatar_url: avatarURL,

      avatar_frame_url: avatarFrameURL,
      avatarFrameUrl: avatarFrameURL,

      status: String(
        user.status ||
        (
          user.type === "customer_service"
            ? "Customer service"
            : user.type === "group"
              ? "Group conversation"
              : "Friend"
        )
      ),

      type: user.type || "friend",

      conversationId:
        user.conversationId ||
        user.conversation_id ||
        null,

      metadata: user.metadata || null
    };

    currentMessagePage = "chat";

    messageModalContent.classList.remove(
      "message-home"
    );

    messageModalContent.classList.add(
      "message-inner-page"
    );

    clearNavigationSelection();

    /*
     * Update the header before hiding the page. If the
     * selected Chat button has focus, hideAllMessagePages()
     * can then move focus to the updated back button.
     */
    setMessageHeader(true);

    hideAllMessagePages();

    chatPage.hidden = false;

    chatPage.classList.add(
      "active",
      "is-active"
    );

    chatPage.setAttribute(
      "aria-hidden",
      "false"
    );

    /*
     * Pass the resolved avatar and frame URLs to chat.js.
     */
    if (typeof window.initializeChatPage === "function") {
      try {
        const result = window.initializeChatPage({
          ...currentChatUser
        });

        if (
          result &&
          typeof result.catch === "function"
        ) {
          result.catch(function (error) {
            console.error(
              "U9 Message: Chat initialization failed.",
              error
            );
          });
        }
      } catch (error) {
        console.error(
          "U9 Message: Chat initialization failed.",
          error
        );
      }
    } else {
      console.warn(
        "U9 Message: chat.js has not registered initializeChatPage()."
      );
    }

    dispatchMessageEvent("u9:message:chat-opened", {
      target: { ...currentChatUser }
    });

    return true;
  }

  /* =================================================
     MESSAGE EVENT
  ================================================= */

  function dispatchMessageEvent(name, detail) {
    window.dispatchEvent(
      new CustomEvent(name, {
        detail: detail || {}
      })
    );
  }

  /* =================================================
     CLOSE CHAT PAGE
  ================================================= */

  function closeMessageChat() {
    /*
     * Move focus out of the chat before chat.js hides it.
     */
    moveFocusOutOfPages();

    const returnPage = window.messageChatReturnPage;

    window.messageChatReturnPage = null;

    stopCurrentChat();

    currentChatUser = null;
    currentMessagePage = null;

    if (
      returnPage &&
      messagePageConfig[returnPage]
    ) {
      return switchMessagePage(returnPage);
    }

    return showMessageHome();
  }

  /* =================================================
     HEADER BUTTON

     Home:
       Close the Message modal.

     Inner page:
       Return to Message home.

     Chat page:
       Return to the page that opened Chat.
  ================================================= */

  function handleMessageHeaderButton() {
    if (currentMessagePage === "chat") {
      closeMessageChat();
      return;
    }

    if (currentMessagePage !== null) {
      showMessageHome();
      return;
    }

    if (
      window.U9WindowManager &&
      typeof window.U9WindowManager.close === "function"
    ) {
      window.U9WindowManager.close("message");
    } else {
      closeMessageModal();
    }
  }

  /* =================================================
     OPEN MODAL
  ================================================= */

  function openMessageModal() {
    if (!messageModal || !messageModalContent) {
      console.warn(
        "U9 Message: Modal elements are missing."
      );

      return false;
    }

    if (closeAnimationTimer !== null) {
      clearTimeout(closeAnimationTimer);
      closeAnimationTimer = null;
    }

    messageModal.classList.remove("modal-closing");

    showMessageHome();

    messageModal.classList.add("modal-open");

    return true;
  }

  /* =================================================
     CLOSE MODAL
  ================================================= */

  function closeMessageModal() {
    if (!messageModal || !messageModalContent) {
      return false;
    }

    if (
      !messageModal.classList.contains("modal-open")
    ) {
      return true;
    }

    /*
     * Clean up the open conversation before closing.
     */
    if (currentMessagePage === "chat") {
      showMessageHome();
    }

    messageModal.classList.remove("modal-open");

    messageModal.classList.add("modal-closing");

    if (closeAnimationTimer !== null) {
      clearTimeout(closeAnimationTimer);
      closeAnimationTimer = null;
    }

    function finishClose() {
      if (
        !messageModal.classList.contains("modal-closing")
      ) {
        return;
      }

      messageModal.classList.remove("modal-closing");

      messageModalContent.removeEventListener(
        "transitionend",
        handleCloseTransition
      );

      if (closeAnimationTimer !== null) {
        clearTimeout(closeAnimationTimer);
        closeAnimationTimer = null;
      }
    }

    function handleCloseTransition(event) {
      if (
        event.target !== messageModalContent ||
        event.propertyName !== "transform"
      ) {
        return;
      }

      finishClose();
    }

    messageModalContent.addEventListener(
      "transitionend",
      handleCloseTransition
    );

    closeAnimationTimer = setTimeout(
      finishClose,
      700
    );

    return true;
  }

  /* =================================================
     NAVIGATION EVENTS
  ================================================= */

  function initializeMessageNavigation() {
    if (!messageNavigation || !messagePagesContainer) {
      console.warn(
        "U9 Message: Navigation or page container is missing."
      );

      return false;
    }

    const elements = getMessagePageElements();

    Object.keys(elements).forEach(function (pageKey) {
      const button = elements[pageKey].button;

      if (!button) {
        console.warn(
          "U9 Message: Navigation button is missing:",
          pageKey
        );

        return;
      }

      if (
        button.dataset.messageNavigationBound === "true"
      ) {
        return;
      }

      button.dataset.messageNavigationBound = "true";

      button.addEventListener("click", function () {
        switchMessagePage(pageKey);
      });
    });

    if (
      messageModalClose &&
      messageModalClose.dataset.messageCloseBound !== "true"
    ) {
      messageModalClose.dataset.messageCloseBound = "true";

      messageModalClose.addEventListener(
        "click",
        handleMessageHeaderButton
      );
    }

    showMessageHome();

    return true;
  }

  /* =================================================
     WINDOW MANAGER
  ================================================= */

  function registerMessageWindowManager() {
    if (
      !window.U9WindowManager ||
      typeof window.U9WindowManager.register !== "function"
    ) {
      console.warn(
        "U9 Message: U9WindowManager is not available yet."
      );

      return false;
    }

    window.U9WindowManager.register("message", {
      open: openMessageModal,

      close: closeMessageModal,

      isOpen: function () {
        if (!messageModal) {
          return false;
        }

        return (
          messageModal.classList.contains("modal-open") ||
          messageModal.classList.contains("modal-closing")
        );
      }
    });

    return true;
  }

  /* =================================================
     PUBLIC API
  ================================================= */

  window.openMessageModal = openMessageModal;
  window.closeMessageModal = closeMessageModal;
  window.showMessageHome = showMessageHome;
  window.switchMessagePage = switchMessagePage;
  window.openMessageChat = openMessageChat;
  window.closeMessageChat = closeMessageChat;

  window.getCurrentMessageChatUser = function () {
    return currentChatUser
      ? { ...currentChatUser }
      : null;
  };

  window.getCurrentMessagePage = function () {
    return currentMessagePage;
  };

  /* =================================================
     INITIALIZE
  ================================================= */

  function initializeMessageModal() {
    if (messageInitialized) {
      return;
    }

    messageInitialized = true;

    initializeMessageNavigation();
    registerMessageWindowManager();
  }

  if (document.readyState === "loading") {
    document.addEventListener(
      "DOMContentLoaded",
      initializeMessageModal,
      { once: true }
    );
  } else {
    initializeMessageModal();
  }

})();
